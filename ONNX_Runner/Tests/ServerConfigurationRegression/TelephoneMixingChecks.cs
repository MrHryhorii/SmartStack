using System.Runtime.InteropServices;
using ONNX_Runner.Models;
using ONNX_Runner.Services;

internal static class TelephoneMixingChecks
{
    // Frozen historical wet moments protect the previous regression limits across the revised mixer.
    // Current eased-path moments and synthetic routing are checked independently as well.
    /// <summary>Checks measured midpoint windows, path errors, reversals and unchanged Telephone structure.</summary>
    internal static void Run(Action<string, Action> check)
    {
        check("Telephone gains preserve exact endpoints and bypass", () =>
        {
            foreach (float amount in new[] { -1f, 0f, .001f, float.NaN, 1f, 2f, float.PositiveInfinity })
            {
                Dsp.TelephoneGains(amount, out float dry, out float wet);
                bool full = amount >= 1;
                Require(dry == (full ? 0f : 1f) && wet == (full ? 1f : 0f), "Endpoint gain changed.");
                Require(Dsp.TelephoneCrossfade(.25f, -.75f, dry, wet) == (full ? -.75f : .25f),
                    "Endpoint mixing changed the selected signal.");
            }
        });
        check("Telephone gains remain finite and their wet share increases monotonically", () =>
        {
            float previous = 0;
            for (int i = 101; i < 100000; i++)
            {
                float t = i / 100000f;
                Dsp.TelephoneGains(t, out float dry, out float wet);
                Require(float.IsFinite(dry) && float.IsFinite(wet) && dry >= 0 && wet >= 0, "Invalid gain.");
                float share = wet / (dry + wet);
                Require(share >= previous - 3e-7f, "Increasing intensity reduced the wet share.");
                previous = share;
            }
        });
        check("Telephone rational gains retain their fitted midpoint and smooth local slopes", () =>
        {
            const float h = .001f;
            Dsp.TelephoneGains(.5f, out float d, out float w);
            Dsp.TelephoneGains(.5f - h, out float dl, out float wl);
            Dsp.TelephoneGains(.5f - 2 * h, out float dll, out float wll);
            Dsp.TelephoneGains(.5f + h, out float dr, out float wr);
            Dsp.TelephoneGains(.5f + 2 * h, out float drr, out float wrr);
            Require(Math.Abs(d - 0.80619398150939992) < 1e-7 && Math.Abs(w - 0.57478678600829058) < 1e-7, "The accepted midpoint changed.");
            Require(Math.Abs((3 * d - 4 * dl + dll) / (2 * h) - (-0.74729824222052055)) < .002
                && Math.Abs((-3 * d + 4 * dr - drr) / (2 * h) - (-0.74729824222052055)) < .002
                && Math.Abs((3 * w - 4 * wl + wll) / (2 * h) - (1.3827105392897778)) < .002
                && Math.Abs((-3 * w + 4 * wr - wrr) / (2 * h) - (1.3827105392897778)) < .002,
                "The midpoint derivatives are not smooth.");
            Dsp.TelephoneGains(MathF.BitDecrement(.5f), out float beforeDry, out float beforeWet);
            Dsp.TelephoneGains(MathF.BitIncrement(.5f), out float afterDry, out float afterWet);
            Require(Math.Abs(beforeDry - afterDry) < 5e-7 && Math.Abs(beforeWet - afterWet) < 5e-7,
                "The continuous rational curve has a midpoint discontinuity.");
        });
        check("Telephone gain evaluation and prepared mixing allocate zero managed bytes", () =>
        {
            double sum = 0;
            for (int i = 0; i < 20000; i++) sum += Sample(i);
            long before = GC.GetAllocatedBytesForCurrentThread();
            for (int i = 0; i < 20000; i++) sum += Sample(i);
            long allocated = GC.GetAllocatedBytesForCurrentThread() - before;
            Require(allocated == 0 && double.IsFinite(sum), $"Prepared mixing allocated {allocated} bytes.");

            static float Sample(int i)
            {
                Dsp.TelephoneGains(i % 1001 / 1000f, out float dry, out float wet);
                return Dsp.TelephoneCrossfade(.2f, -.1f, dry, wet);
            }
        });
        Require(VoiceReferences.Length == 48 && SyntheticReferences.Length == 12 && DenseSteps.Length == 48,
            "Independent recorded fixtures are incomplete.");
        foreach (var r in VoiceReferences)
        {
            check($"Telephone midpoint escape stays below its declared 0.55 dB limit for {r.Name}", () =>
            {
                double y = RecordedLevel(r, r.Points[10]);
                double escape = Math.Max(Math.Min(0, r.FullChangeDb) - y, 0) + Math.Max(y - Math.Max(0, r.FullChangeDb), 0);
                Require(escape < .55, "Midpoint exceeded the declared escape limit.");
            });
            check($"Frozen mixer: Telephone recorded primary path stays within 1.81 dB of its own guide for {r.Name}", () =>
            {
                Require(r.Points.Length == 21, "Missing primary measurements.");
                double oldError = 0, newError = 0;
                foreach (var point in r.Points)
                {
                    double error = Math.Abs(RecordedLevel(r, point) - point.Amount * r.FullChangeDb);
                    Require(error < 1.81, "Recorded path exceeded its declared reference band.");
                    newError += error; oldError += Math.Abs(point.OriginalChangeDb - point.Amount * r.FullChangeDb);
                }
                Require((newError - oldError) / r.Points.Length < .21, "A recording exceeded the allowed common-curve tradeoff.");
            });
            check($"Frozen mixer: Telephone recorded primary reverse steps stay below 0.7001 dB for {r.Name}", () =>
            {
                for (int i = 1; i < r.Points.Length; i++)
                    Require(Math.Sign(r.FullChangeDb) * (RecordedLevel(r, r.Points[i - 1]) - RecordedLevel(r, r.Points[i])) < .7001, "A primary reverse step exceeded its declared budget.");
            });
        }
        foreach (var r in DenseSteps)
        {
            check($"Telephone retains its independent dense reversal control for {r.Name}", () =>
            {
                Require(Math.Abs(TelephoneCurveChecks.HistoricalEqualPowerLevel(r.Name, r.From) - r.FromDb) < 4e-6
                    && Math.Abs(TelephoneCurveChecks.HistoricalEqualPowerLevel(r.Name, r.To) - r.ToDb) < 4e-6,
                    "The original dense reference input changed.");
                double from = TelephoneCurveChecks.HistoricalLevel(r.Name, r.From);
                double to = TelephoneCurveChecks.HistoricalLevel(r.Name, r.To);
                Require(r.Direction * (from - to) < .18, "A recorded dense reverse step exceeded its declared budget.");
            });
        }
        foreach (var r in SyntheticReferences)
        {
            check($"Telephone routing matches independent PCM at {r.Rate} Hz and {r.Amount:R}", () =>
            {
                float[] signal = Signal(r.Rate, r.Rate * 3);
                NewEngine(r.Rate).ApplyEffect(signal, VoiceEffectType.Telephone, r.Amount);
                double power = 0;
                foreach (float x in signal) power += x * (double)x;
                Require(Math.Abs(10 * Math.Log10(power / signal.Length) - r.RmsDbfs) < .002,
                    "Production output differs from the frozen pre-update waveform times the independent gain.");
            });
        }
        check("Frozen mixer: Telephone corpus mean improves its path and retains primary/dense ordering controls", () =>
        {
            double oldError = 0, newError = 0, previous = 0;
            for (int i = 0; i < 21; i++)
            {
                double oldMean = 0, newMean = 0, guide = 0;
                foreach (var r in VoiceReferences)
                {
                    var point = r.Points[i];
                    oldMean += point.OriginalChangeDb / VoiceReferences.Length;
                    newMean += RecordedLevel(r, point) / VoiceReferences.Length;
                    guide += point.Amount * r.FullChangeDb / VoiceReferences.Length;
                }
                Require(newMean <= previous + 1e-5, "The primary corpus mean reversed.");
                previous = newMean;
                oldError += Math.Abs(oldMean - guide); newError += Math.Abs(newMean - guide);
            }
            Require(newError < oldError, "The correction no longer improves the corpus mean.");
            int midpointPasses = VoiceReferences.Count(r => RecordedLevel(r, r.Points[10]) >= Math.Min(0, r.FullChangeDb)
                && RecordedLevel(r, r.Points[10]) <= Math.Max(0, r.FullChangeDb));
            Require(midpointPasses >= 41, "The recorded midpoint window count regressed.");
            for (int i = 1; i < MeanDense.Length; i++)
                Require(CorrectedLevel(MeanDense[i]) - CorrectedLevel(MeanDense[i - 1]) < .00152, "The dense corpus mean exceeded its reverse-step budget.");
        });
        foreach (int rate in new[] { 8000, 22050, 48000 })
        {
            check($"Telephone changing intensity is independent of stream partitions at {rate} Hz", () =>
            {
                float[] amounts = [0f, .001f, .00101f, .025f, .125f, .4995f, .5f, .5005f, .875f, .99f, 1f, .45f];
                int size = rate / 8;
                float[] whole = Signal(rate, size * amounts.Length), split = (float[])whole.Clone();
                var a = NewEngine(rate); var b = NewEngine(rate);
                for (int section = 0; section < amounts.Length; section++)
                {
                    a.ApplyEffect(whole.AsSpan(section * size, size), VoiceEffectType.Telephone, amounts[section]);
                    for (int i = 0; i < size; i += 257)
                        b.ApplyEffect(split.AsSpan(section * size + i, Math.Min(257, size - i)), VoiceEffectType.Telephone, amounts[section]);
                }
                Require(MemoryMarshal.AsBytes(whole.AsSpan()).SequenceEqual(MemoryMarshal.AsBytes(split.AsSpan())),
                    "Streaming partitions changed the effect output.");
            });
            check($"Telephone warm bypass remains clean at {rate} Hz", () =>
            {
                var engine = NewEngine(rate); float[] input = Signal(rate, rate / 2), warm = (float[])input.Clone();
                engine.ApplyEffect(warm, VoiceEffectType.Telephone, .65f);
                foreach (float amount in new[] { 0f, .001f })
                {
                    float[] output = (float[])input.Clone(); engine.ApplyEffect(output, VoiceEffectType.Telephone, amount);
                    Require(MemoryMarshal.AsBytes(input.AsSpan()).SequenceEqual(MemoryMarshal.AsBytes(output.AsSpan())), "Warm bypass changed clean samples.");
                }
            });
        }
    }

    /// <summary>Evaluates prepared weights against recorded powers, including their cross term.</summary>
    private static double RecordedLevel(VoiceReference reference, (float Amount, double WetPower, double Cross, double OriginalChangeDb) point)
    {
        Dsp.TelephoneGains(point.Amount, out float dry, out float wet);
        double power = dry * (double)dry * reference.DryPower + wet * (double)wet * point.WetPower
            + 2 * dry * (double)wet * point.Cross;
        return 10 * Math.Log10(power / reference.DryPower);
    }

    /// <summary>Evaluates old controls from independent moments without assuming a common gain.</summary>
    private static double CorrectedLevel((float Amount, double OriginalChangeDb) point)
    {
        Require(Math.Abs(TelephoneCurveChecks.HistoricalMean(point.Amount, true) - point.OriginalChangeDb) < 4e-6,
            "The original dense catalog reference input changed.");
        return TelephoneCurveChecks.HistoricalMean(point.Amount);
    }

    /// <summary>Creates the frozen multi-band synthetic input without stored audio assets.</summary>
    private static float[] Signal(int rate, int count)
    {
        var signal = new float[count];
        for (int i = 0; i < count; i++)
        {
            double t = (double)i / rate;
            signal[i] = (float)((.18 * Math.Sin(2 * Math.PI * 110 * t) + .08 * Math.Sin(2 * Math.PI * 330 * t)
                + .05 * Math.Sin(2 * Math.PI * 1700 * t) + .03 * Math.Sin(2 * Math.PI * Math.Min(3200, rate * .3) * t))
                * (.7 + .3 * Math.Sin(2 * Math.PI * .73 * t)));
        }
        return signal;
    }

    /// <summary>Creates replayable state for routing checks.</summary>
    private static AudioEffectsEngine NewEngine(int rate)
    {
        var engine = new AudioEffectsEngine(new(), rate); engine.Reset(123456); return engine;
    }

    /// <summary>Reports a violated signal contract to the console runner.</summary>
    private static void Require(bool condition, string message)
    {
        if (!condition) throw new InvalidOperationException(message);
    }

