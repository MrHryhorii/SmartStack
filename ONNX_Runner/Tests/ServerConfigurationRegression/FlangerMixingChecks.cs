using System.Runtime.InteropServices;
using ONNX_Runner.Models;
using ONNX_Runner.Services;

internal static class FlangerMixingChecks
{
    /// <summary>Checks measured midpoint windows, path errors, reversals and unchanged Flanger structure.</summary>
    internal static void Run(Action<string, Action> check)
    {
        check("Flanger gain retains exact endpoints, invalid-input guard and internal dry endpoint", () =>
        {
            foreach (float t in new[] { -1f, 0f, .001f, float.NaN, 1f, 2f, float.PositiveInfinity })
                Require(Dsp.FlangerGain(t) == 1f, "Endpoint or invalid gain changed.");
            Require(Dsp.FlangerCrossfade(.25f, -.75f, 0f, 1f) == .25f, "The internal zero endpoint changed clean audio.");
        });
        check("Flanger prepared gain remains finite and positive", () =>
        {
            for (int i = 0; i <= 100000; i++)
            {
                float g = Dsp.FlangerGain(i / 100000f);
                Require(float.IsFinite(g) && g > 0, "Invalid gain.");
            }
        });
        check("Flanger polynomial halves share their midpoint value and derivative", () =>
        {
            const float h = .001f;
            double middle = Dsp.FlangerGain(.5f);
            double left = (3 * middle - 4 * Dsp.FlangerGain(.5f - h) + Dsp.FlangerGain(.5f - 2 * h)) / (2 * h);
            double right = (-3 * middle + 4 * Dsp.FlangerGain(.5f + h) - Dsp.FlangerGain(.5f + 2 * h)) / (2 * h);
            Require(Math.Abs(middle - 1.040952124642789) < 1e-7, "The midpoint gain changed.");
            Require(Math.Abs(left - 0.17634376179081873) < .003 && Math.Abs(right - 0.17634376179081873) < .003,
                "The gain halves do not share the fitted derivative.");
            Require(Math.Abs(Dsp.FlangerGain(MathF.BitDecrement(.5f)) - Dsp.FlangerGain(MathF.BitIncrement(.5f))) < 5e-7,
                "The midpoint gain is discontinuous.");
        });
        check("Flanger preparation and mixing allocate zero managed bytes", () =>
        {
            double sum = 0;
            for (int i = 0; i < 20000; i++) sum += Sample(i);
            long before = GC.GetAllocatedBytesForCurrentThread();
            for (int i = 0; i < 20000; i++) sum += Sample(i);
            Require(GC.GetAllocatedBytesForCurrentThread() - before == 0 && double.IsFinite(sum), "Prepared mixing allocated memory.");
            static float Sample(int i)
            {
                float t = i % 1001 / 1000f;
                return Dsp.FlangerCrossfade(.2f, -.1f, t, Dsp.FlangerGain(t));
            }
        });
        Require(VoiceReferences.Length == 48 && SyntheticReferences.Length == 12 && DenseSteps.Length == 48,
            "Independent recorded fixtures are incomplete.");
        foreach (var r in VoiceReferences)
        {
            check($"Flanger midpoint escape stays below its declared 0.37 dB limit for {r.Name}", () =>
            {
                double y = Level(r.Points[10]);
                double escape = Math.Max(Math.Min(0, r.FullChangeDb) - y, 0) + Math.Max(y - Math.Max(0, r.FullChangeDb), 0);
                Require(escape < .37, "Midpoint exceeded the declared escape limit.");
            });
            check($"Flanger recorded primary path stays within 1.81 dB of its own guide for {r.Name}", () =>
            {
                Require(r.Points.Length == 21, "Missing primary measurements.");
                double oldError = 0, newError = 0;
                foreach (var point in r.Points)
                {
                    double error = Math.Abs(Level(point) - point.Amount * r.FullChangeDb);
                    Require(error < 1.81, "Recorded path exceeded its declared reference band.");
                    newError += error; oldError += Math.Abs(point.OriginalChangeDb - point.Amount * r.FullChangeDb);
                }
                Require((newError - oldError) / r.Points.Length < .26, "A recording exceeded the allowed common-curve tradeoff.");
            });
            check($"Flanger recorded primary reverse steps stay below 0.64 dB for {r.Name}", () =>
            {
                for (int i = 1; i < r.Points.Length; i++)
                    Require(Math.Sign(r.FullChangeDb) * (Level(r.Points[i - 1]) - Level(r.Points[i])) < .64, "A primary reverse step exceeded its declared budget.");
            });
        }
        foreach (var r in DenseSteps)
        {
            check($"Flanger retains its independent dense reversal control for {r.Name}", () =>
            {
                double from = r.FromDb + 20 * Math.Log10(Dsp.FlangerGain(r.From));
                double to = r.ToDb + 20 * Math.Log10(Dsp.FlangerGain(r.To));
                Require(r.Direction * (from - to) < .073, "A recorded dense reverse step exceeded its declared budget.");
            });
        }
        foreach (var r in SyntheticReferences)
        {
            check($"Flanger routing matches independent PCM at {r.Rate} Hz and {r.Amount:R}", () =>
            {
                float[] signal = Signal(r.Rate, r.Rate * 3);
                NewEngine(r.Rate).ApplyEffect(signal, VoiceEffectType.Flanger, r.Amount);
                double power = 0;
                foreach (float x in signal) power += x * (double)x;
                Require(Math.Abs(10 * Math.Log10(power / signal.Length) - r.RmsDbfs) < .002,
                    "Production output differs from the frozen pre-update waveform times the independent gain.");
            });
        }
        check("Flanger corpus mean improves its path and retains primary/dense ordering controls", () =>
        {
            double oldError = 0, newError = 0, previous = 0;
            for (int i = 0; i < 21; i++)
            {
                double oldMean = 0, newMean = 0, guide = 0;
                foreach (var r in VoiceReferences)
                {
                    var point = r.Points[i];
                    oldMean += point.OriginalChangeDb / VoiceReferences.Length;
                    newMean += Level(point) / VoiceReferences.Length;
                    guide += point.Amount * r.FullChangeDb / VoiceReferences.Length;
                }
                Require(newMean >= previous - 1e-5, "The primary corpus mean reversed.");
                previous = newMean;
                oldError += Math.Abs(oldMean - guide); newError += Math.Abs(newMean - guide);
            }
            Require(newError < oldError, "The correction no longer improves the corpus mean.");
            int midpointPasses = VoiceReferences.Count(r => Level(r.Points[10]) >= Math.Min(0, r.FullChangeDb)
                && Level(r.Points[10]) <= Math.Max(0, r.FullChangeDb));
            Require(midpointPasses >= 36, "The recorded midpoint window count regressed.");
            for (int i = 1; i < MeanDense.Length; i++)
                Require(Level(MeanDense[i - 1]) - Level(MeanDense[i]) < .00151, "The dense corpus mean exceeded its reverse-step budget.");
        });
        foreach (int rate in new[] { 8000, 22050, 48000 })
        {
            check($"Flanger changing intensity is independent of stream partitions at {rate} Hz", () =>
            {
                float[] amounts = [0f, .001f, .00101f, .025f, .125f, .4995f, .5f, .5005f, .875f, .99f, 1f, .45f];
                int size = rate / 8;
                float[] whole = Signal(rate, size * amounts.Length), split = (float[])whole.Clone();
                var a = NewEngine(rate); var b = NewEngine(rate);
                for (int section = 0; section < amounts.Length; section++)
                {
                    a.ApplyEffect(whole.AsSpan(section * size, size), VoiceEffectType.Flanger, amounts[section]);
                    for (int i = 0; i < size; i += 257)
                        b.ApplyEffect(split.AsSpan(section * size + i, Math.Min(257, size - i)), VoiceEffectType.Flanger, amounts[section]);
                }
                Require(MemoryMarshal.AsBytes(whole.AsSpan()).SequenceEqual(MemoryMarshal.AsBytes(split.AsSpan())),
                    "Streaming partitions changed the effect output.");
            });
            check($"Flanger warm bypass remains clean at {rate} Hz", () =>
            {
                var engine = NewEngine(rate); float[] input = Signal(rate, rate / 2), warm = (float[])input.Clone();
                engine.ApplyEffect(warm, VoiceEffectType.Flanger, .65f);
                foreach (float amount in new[] { 0f, .001f })
                {
                    float[] output = (float[])input.Clone(); engine.ApplyEffect(output, VoiceEffectType.Flanger, amount);
                    Require(MemoryMarshal.AsBytes(input.AsSpan()).SequenceEqual(MemoryMarshal.AsBytes(output.AsSpan())), "Warm bypass changed clean samples.");
                }
            });
        }
    }

    /// <summary>Applies the actual scalar gain to an independently measured original relative RMS.</summary>
    private static double Level((float Amount, double OriginalChangeDb) point)
    {
        return point.OriginalChangeDb + 20 * Math.Log10(Dsp.FlangerGain(point.Amount));
    }

    /// <summary>Creates the frozen multi-band synthetic input without stored audio assets.</summary>
    private static float[] Signal(int rate, int count)
    {
        var signal = new float[count];
        for (int i = 0; i < count; i++)
        {
            double t = (double)i / rate;
            signal[i] = (float)((.18 * Math.Sin(2 * Math.PI * 110 * t) + .08 * Math.Sin(2 * Math.PI * 330 * t)
                + .05 * Math.Sin(2 * Math.PI * 1700 * t) + .03 * Math.Sin(2 * Math.PI * Math.Min(3200, rate * .3) * t))
                * (.7 + .3 * Math.Sin(2 * Math.PI * .73 * t)));
        }
        return signal;
    }

    /// <summary>Creates replayable state for routing checks.</summary>
    private static AudioEffectsEngine NewEngine(int rate)
    {
        var engine = new AudioEffectsEngine(new(), rate); engine.Reset(123456); return engine;
    }

    /// <summary>Reports a violated signal contract to the console runner.</summary>
    private static void Require(bool condition, string message)
    {
        if (!condition) throw new InvalidOperationException(message);
    }

